"""Assemble the course content: writes content/m*.json, mindmaps.py, qbank.py and qhooks.py from go*.py."""
import json, os, glob, importlib, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
MODS = []
for name in ["go1a", "go1b", "go2a", "go2b", "go3a", "go3b"]:
    if os.path.exists(os.path.join(HERE, name + ".py")): MODS += importlib.import_module(name).M
for f in glob.glob(os.path.join(HERE, "m[0-9]*.json")): os.remove(f)
MM, QB, HK = {}, [], {}
PLACES = {1: ("Your home", "Walk through your own home, front door to garden gate. In each room, picture the strange scene and let it hand you the module's core idea."),
          2: ("A modelling workshop", "Walk through a busy workshop where crowd models are built, bench by bench. Each bench holds one model with its own odd scene."),
          3: ("A pilgrimage route", "Walk the route of a great pilgrimage, from the arrival camp to the final rite. Each stop is one research module.")}
PAL = {g: {"place": PLACES[g][0], "intro": PLACES[g][1], "stations": []} for g in (1, 2, 3)}
for m in MODS:
    secs = m["sections"]
    MM[m["id"]] = [s["mm"] for s in secs]
    for k, q, a, it, hk in m["qb"]:
        QB.append((m["id"], k, q, a)); HK.setdefault(m["id"], []).append((it, hk))
    PAL[m["go"]]["stations"].append((m["id"], m["palace"][0], m["palace"][1]))
    out = {k: v for k, v in m.items() if k not in ("qb", "palace")}
    out["sections"] = [{"heading": s["heading"], "html": s["html"]} for s in secs]
    json.dump(out, open(os.path.join(HERE, "m" + m["id"].replace(".", "") + ".json"), "w"), ensure_ascii=False, indent=1)
open(os.path.join(HERE, "mindmaps.py"), "w").write('"""Generated by make.py: one mind map per module, one branch per section."""\nMM = ' + repr(MM) + "\n")
open(os.path.join(HERE, "qbank.py"), "w").write('"""Generated by make.py: (module, kind, question, model answer)."""\nQ = ' + repr(QB) + "\n")
open(os.path.join(HERE, "qhooks.py"), "w").write('"""Generated by make.py: (intuition, memory hook) per question, and one memory palace per go."""\nH = ' + repr(HK) + "\nPALACE = " + repr(PAL) + "\n")
print(len(MODS), "modules,", len(QB), "questions")
